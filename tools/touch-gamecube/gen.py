#!/usr/bin/env python3
"""Builds platform/pad/touch_gamecube.h: the GameCube touch style's shapes and
letters as polygons, traced (potrace) from the pictures in this folder.

The button shapes come from m-overlay by Bkacjios (MIT, LICENSE-m-overlay);
l-, r- and rplus-trigger.png (L, R, R+) are Mareshine's own. Letters are DejaVu Sans Bold.
Run: python3 tools/touch-gamecube/gen.py (needs Pillow and potrace).
"""
import json
import os
import subprocess
import sys
import tempfile

from PIL import Image, ImageDraw, ImageFilter, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "platform", "pad", "touch_gamecube.h")
OUT_JAVA = os.path.join(HERE, "..", "..", "android", "app", "src", "main", "java", "io", "github", "them3dium",
                        "mareshine", "GcShapes.java")
FONT = "/usr/share/fonts/TTF/DejaVuSans-Bold.ttf"

SHAPES = [  # name in the header, picture
    ("GATE", "joystick-gate-filled.png"),
    ("KNOB", "joystick-filled.png"),
    ("CGATE", "c-stick-gate-filled.png"),
    ("CKNOB", "c-stick-solid.png"),
    ("A", "a-pressed.png"),
    ("B", "b-pressed.png"),
    ("X", "x-pressed.png"),
    ("Y", "y-pressed.png"),
    ("Z", "z-pressed.png"),
    ("START", "start-pressed.png"),
    ("DPAD", "d-pad-gate-filled.png"),
    ("TRIGGER_L", "l-trigger.png"),
    ("TRIGGER_R", "r-trigger.png"),
    ("TRIGGER_RPLUS", "rplus-trigger.png"),
]
LETTERS = "ABXYZCLRS+"


def mask_of(path):
    a = Image.open(os.path.join(HERE, path)).convert("RGBA").split()[3]
    if max(a.size) > 256:  # as fine as the 128 px pictures; more only adds points
        k = 256 / max(a.size)
        a = a.resize((round(a.size[0] * k), round(a.size[1] * k)), Image.LANCZOS)
    a = a.point(lambda v: 255 if v > 127 else 0)
    if path == "lr-trigger.png":  # the bottom edge straight
        bb = a.getbbox()
        a = a.crop(bb)
        w, h = a.size
        px = a.load()
        row = h - 10
        xs = [x for x in range(w) if px[x, row] > 0]
        for y in range(row, h):
            for x in range(min(xs), max(xs) + 1):
                px[x, y] = 255
    return a


def trace(mask, scale=4):
    big = mask.resize((mask.size[0] * scale, mask.size[1] * scale), Image.LANCZOS)
    big = big.filter(ImageFilter.GaussianBlur(scale * 0.6)).point(lambda v: 0 if v > 127 else 255).convert("1")
    with tempfile.TemporaryDirectory() as d:
        pbm = os.path.join(d, "m.pbm")
        big.save(pbm)
        out = subprocess.run(["potrace", "-b", "geojson", "-t", "4", "-O", "0.4", pbm, "-o", "-"],
                             capture_output=True, text=True, check=True).stdout
    rings = []
    for f in json.loads(out)["features"]:
        for ring in f["geometry"]["coordinates"]:
            rings.append([(x / scale, y / scale) for x, y in ring[:-1]])
    return rings


def normalize(rings):
    xs = [x for r in rings for x, _ in r]
    ys = [y for r in rings for _, y in r]
    cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    half = max(max(xs) - min(xs), max(ys) - min(ys)) / 2
    # potrace's y grows upwards: flip back to the picture's
    return [[((x - cx) / half, -(y - cy) / half) for x, y in r] for r in rings]


def pole(mask):
    """The widest place inside the shape (where its letter goes) and how far it
    is from the edge, both in the shape's [-1, 1] units."""
    w, h = mask.size
    px = mask.load()
    big = 1e9
    d = [[big if px[x, y] > 0 else 0.0 for x in range(w)] for y in range(h)]
    at = lambda x, y: d[y][x] if 0 <= x < w and 0 <= y < h else 0.0
    for y in range(h):
        for x in range(w):
            if d[y][x]:
                d[y][x] = min(d[y][x], at(x - 1, y) + 1, at(x, y - 1) + 1, at(x - 1, y - 1) + 1.414, at(x + 1, y - 1) + 1.414)
    for y in range(h - 1, -1, -1):
        for x in range(w - 1, -1, -1):
            if d[y][x]:
                d[y][x] = min(d[y][x], at(x + 1, y) + 1, at(x, y + 1) + 1, at(x + 1, y + 1) + 1.414, at(x - 1, y + 1) + 1.414)
    x0, y0, x1, y1 = mask.getbbox()
    cx, cy, half = (x0 + x1) / 2, (y0 + y1) / 2, max(x1 - x0, y1 - y0) / 2
    # of the places nearly as wide as the widest, the one nearest the middle
    # (a pill is as wide all along)
    top = max(v for row in d for v in row)
    best, bx, by = min(((d[y][x], x, y) for y in range(h) for x in range(w) if d[y][x] >= top - 1.0),
                       key=lambda t: (t[1] - cx) ** 2 + (t[2] - cy) ** 2)
    return ((bx + 0.5 - cx) / half, (by + 0.5 - cy) / half, best / half)


def emit_java(shapes):
    """GcShapes.java: the same shapes for the app's layout editor, as text (a
    class's constants may not hold this many numbers)."""
    out = ["// Generated by tools/touch-gamecube/gen.py; do not edit.",
           "// The GameCube touch style's shapes (see platform/pad/touch_gamecube.h) for the",
           "// layout editor: each ring's points x,y in [-1, 1] (y down), rings split by ';',",
           "// and the widest place inside (its letter's middle) with its distance to the edge.",
           "package io.github.them3dium.mareshine;", "", "final class GcShapes {",
           "    static final String[] NAMES = { " + ", ".join('"%s"' % n for n, _, _ in shapes) + " };",
           "    static final float[][] POLES = { " + ", ".join("{ %.3ff, %.3ff, %.3ff }" % p for _, _, p in shapes) + " };",
           "    static final String[] RINGS = {"]
    for _, rings, _ in shapes:
        out.append('        "' + ";".join(" ".join("%.3f,%.3f" % pt for pt in r) for r in rings) + '",')
    out += ["    };", "", "    private GcShapes() {}", "}"]
    with open(OUT_JAVA, "w") as f:
        f.write("\n".join(out) + "\n")


def letter_mask(ch):
    f = ImageFont.truetype(FONT, 160)
    im = Image.new("L", (220, 220), 0)
    ImageDraw.Draw(im).text((110, 110), ch, font=f, fill=255, anchor="mm")
    return im.crop(im.getbbox())


def emit(name, rings, lines):
    pts, lens = [], []
    for r in rings:
        lens.append(len(r))
        pts += [f"{x:.4f}f, {y:.4f}f" for x, y in r]
    lines.append(f"const float kGc{name}Pts[] = {{ {', '.join(pts)} }};")
    lines.append(f"const unsigned short kGc{name}Rings[] = {{ {', '.join(map(str, lens))} }};")
    return f"{{ kGc{name}Pts, kGc{name}Rings, {len(lens)} }}"


def main():
    lines = ["// Generated by tools/touch-gamecube/gen.py; do not edit.",
             "// Shapes from m-overlay by Bkacjios (MIT, tools/touch-gamecube/LICENSE-m-overlay),",
             "// L/R from Mareshine, letters DejaVu Sans Bold. Polygons in [-1, 1], y down,",
             "// filled even-odd.",
             "#pragma once", "", "struct GcPoly {", "\tconst float* pts;", "\tconst unsigned short* rings;",
             "\tint ringCount;", "};", "", "namespace {"]
    shapes, letters = [], []
    java = []
    for name, pic in SHAPES:
        m = mask_of(pic)
        rings = normalize(trace(m, max(1, round(512 / max(m.size)))))
        shapes.append((name, emit(name, rings, lines)))
        java.append((name, rings, pole(m)))
    emit_java(java)
    for ch in LETTERS:
        letters.append(emit("Letter%d" % LETTERS.index(ch), normalize(trace(letter_mask(ch), 2)), lines))
    lines.append("")
    lines.append("enum GcShape { " + ", ".join("GC_" + n for n, _ in shapes) + ", GC_SHAPE_COUNT };")
    lines.append("const GcPoly kGcShapes[GC_SHAPE_COUNT] = { " + ", ".join(e for _, e in shapes) + " };")
    lines.append(f'const char kGcLetterChars[] = "{LETTERS}";')
    lines.append("const GcPoly kGcLetters[] = { " + ", ".join(letters) + " };")
    lines.append("}  // namespace")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(OUT, sum(len(l) for l in lines), "bytes", file=sys.stderr)


if __name__ == "__main__":
    main()
