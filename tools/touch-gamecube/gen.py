#!/usr/bin/env python3
"""Builds platform/pad/touch_gamecube.h: the GameCube touch style's shapes and
letters as polygons, traced (potrace) from the pictures in this folder.

The button shapes come from m-overlay by Bkacjios (MIT, LICENSE-m-overlay);
lr-trigger.png (L and R) is Mareshine's own. Letters are DejaVu Sans Bold.
Run: python3 tools/touch-gamecube/gen.py (needs Pillow and potrace).
"""
import json
import os
import subprocess
import sys
import tempfile

from PIL import Image, ImageDraw, ImageFilter, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "platform", "pad", "touch_gamecube.h")
FONT = "/usr/share/fonts/TTF/DejaVuSans-Bold.ttf"

SHAPES = [  # name in the header, picture
    ("GATE", "joystick-gate-filled.png"),
    ("KNOB", "joystick-filled.png"),
    ("CGATE", "c-stick-gate-filled.png"),
    ("CKNOB", "c-stick-solid.png"),
    ("A", "a-pressed.png"),
    ("B", "b-pressed.png"),
    ("X", "x-pressed.png"),
    ("Y", "y-pressed.png"),
    ("Z", "z-pressed.png"),
    ("START", "start-pressed.png"),
    ("DPAD", "d-pad-gate-filled.png"),
    ("TRIGGER", "lr-trigger.png"),
]
LETTERS = "ABXYZCLRS"


def mask_of(path):
    a = Image.open(os.path.join(HERE, path)).convert("RGBA").split()[3]
    a = a.point(lambda v: 255 if v > 127 else 0)
    if "trigger" in path:  # the bottom edge straight
        bb = a.getbbox()
        a = a.crop(bb)
        w, h = a.size
        px = a.load()
        row = h - 10
        xs = [x for x in range(w) if px[x, row] > 0]
        for y in range(row, h):
            for x in range(min(xs), max(xs) + 1):
                px[x, y] = 255
    return a


def trace(mask, scale=4):
    big = mask.resize((mask.size[0] * scale, mask.size[1] * scale), Image.LANCZOS)
    big = big.filter(ImageFilter.GaussianBlur(scale * 0.6)).point(lambda v: 0 if v > 127 else 255).convert("1")
    with tempfile.TemporaryDirectory() as d:
        pbm = os.path.join(d, "m.pbm")
        big.save(pbm)
        out = subprocess.run(["potrace", "-b", "geojson", "-t", "4", "-O", "0.4", pbm, "-o", "-"],
                             capture_output=True, text=True, check=True).stdout
    rings = []
    for f in json.loads(out)["features"]:
        for ring in f["geometry"]["coordinates"]:
            rings.append([(x / scale, y / scale) for x, y in ring[:-1]])
    return rings


def normalize(rings):
    xs = [x for r in rings for x, _ in r]
    ys = [y for r in rings for _, y in r]
    cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    half = max(max(xs) - min(xs), max(ys) - min(ys)) / 2
    # potrace's y grows upwards: flip back to the picture's
    return [[((x - cx) / half, -(y - cy) / half) for x, y in r] for r in rings]


def letter_mask(ch):
    f = ImageFont.truetype(FONT, 400)
    im = Image.new("L", (520, 520), 0)
    ImageDraw.Draw(im).text((260, 260), ch, font=f, fill=255, anchor="mm")
    return im.crop(im.getbbox())


def emit(name, rings, lines):
    pts, lens = [], []
    for r in rings:
        lens.append(len(r))
        pts += [f"{x:.4f}f, {y:.4f}f" for x, y in r]
    lines.append(f"const float kGc{name}Pts[] = {{ {', '.join(pts)} }};")
    lines.append(f"const unsigned short kGc{name}Rings[] = {{ {', '.join(map(str, lens))} }};")
    return f"{{ kGc{name}Pts, kGc{name}Rings, {len(lens)} }}"


def main():
    lines = ["// Generated by tools/touch-gamecube/gen.py; do not edit.",
             "// Shapes from m-overlay by Bkacjios (MIT, tools/touch-gamecube/LICENSE-m-overlay),",
             "// L/R from Mareshine, letters DejaVu Sans Bold. Polygons in [-1, 1], y down,",
             "// filled even-odd.",
             "#pragma once", "", "struct GcPoly {", "\tconst float* pts;", "\tconst unsigned short* rings;",
             "\tint ringCount;", "};", "", "namespace {"]
    shapes, letters = [], []
    for name, pic in SHAPES:
        shapes.append((name, emit(name, normalize(trace(mask_of(pic))), lines)))
    for ch in LETTERS:
        letters.append(emit("Letter" + ch, normalize(trace(letter_mask(ch), 1)), lines))
    lines.append("")
    lines.append("enum GcShape { " + ", ".join("GC_" + n for n, _ in shapes) + ", GC_SHAPE_COUNT };")
    lines.append("const GcPoly kGcShapes[GC_SHAPE_COUNT] = { " + ", ".join(e for _, e in shapes) + " };")
    lines.append(f'const char kGcLetterChars[] = "{LETTERS}";')
    lines.append("const GcPoly kGcLetters[] = { " + ", ".join(letters) + " };")
    lines.append("}  // namespace")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(OUT, sum(len(l) for l in lines), "bytes", file=sys.stderr)


if __name__ == "__main__":
    main()
